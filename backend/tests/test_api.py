from datetime import timedelta
from decimal import Decimal

from django.utils import timezone
from rest_framework.test import APITestCase

from apps.accounts.models import User
from apps.clients.models import Client, Lead
from apps.finance.models import Invoice
from apps.projects.models import Project, Task


class BaseAPITest(APITestCase):
    def setUp(self):
        self.admin = User.objects.create_user("boss", password="x" * 8, role="admin")
        self.accountant = User.objects.create_user("acc", password="x" * 8, role="accountant")
        self.specialist = User.objects.create_user("spec", password="x" * 8, role="specialist")
        self.client_obj = Client.objects.create(name="Mijoz")
        self.project = Project.objects.create(client=self.client_obj, name="Loyiha", budget=Decimal("1000"))


class AuthTests(BaseAPITest):
    def test_login_and_me(self):
        r = self.client.post("/api/auth/login/", {"username": "boss", "password": "x" * 8})
        self.assertEqual(r.status_code, 200)
        self.client.credentials(HTTP_AUTHORIZATION=f"Bearer {r.data['access']}")
        me = self.client.get("/api/auth/me/")
        self.assertEqual(me.data["role"], "admin")
        self.assertTrue(me.data["can_see_finance"])

    def test_anonymous_rejected(self):
        self.assertEqual(self.client.get("/api/clients/").status_code, 401)


class PermissionTests(BaseAPITest):
    def test_specialist_cannot_see_finance(self):
        self.client.force_authenticate(self.specialist)
        self.assertEqual(self.client.get("/api/invoices/").status_code, 403)
        self.assertNotIn("finance", self.client.get("/api/reports/dashboard/").data)

    def test_specialist_cannot_create_client_but_can_create_task(self):
        self.client.force_authenticate(self.specialist)
        self.assertEqual(self.client.post("/api/clients/", {"name": "X"}).status_code, 403)
        r = self.client.post("/api/tasks/", {"project": self.project.pk, "title": "Post"})
        self.assertEqual(r.status_code, 201)
        self.assertEqual(Task.objects.get().created_by, self.specialist)

    def test_salary_hidden_from_specialist(self):
        self.client.force_authenticate(self.specialist)
        r = self.client.get(f"/api/users/{self.admin.pk}/")
        self.assertNotIn("salary", r.data)


class FinanceTests(BaseAPITest):
    def setUp(self):
        super().setUp()
        self.client.force_authenticate(self.accountant)

    def _invoice(self, amount="1000"):
        r = self.client.post("/api/invoices/", {"client": self.client_obj.pk, "project": self.project.pk,
                                                "amount": amount, "status": "sent"})
        self.assertEqual(r.status_code, 201, r.data)
        return r.data

    def test_invoice_number_autogenerated(self):
        a, b = self._invoice(), self._invoice()
        year = timezone.localdate().year
        self.assertEqual(a["number"], f"INV-{year}-0001")
        self.assertEqual(b["number"], f"INV-{year}-0002")

    def test_payments_update_status_and_block_overpay(self):
        inv = self._invoice()
        self.client.post("/api/payments/", {"invoice": inv["id"], "amount": "400"})
        self.assertEqual(Invoice.objects.get(pk=inv["id"]).status, "partial")
        r = self.client.post("/api/payments/", {"invoice": inv["id"], "amount": "700"})
        self.assertEqual(r.status_code, 400)
        p = self.client.post("/api/payments/", {"invoice": inv["id"], "amount": "600"})
        self.assertEqual(Invoice.objects.get(pk=inv["id"]).status, "paid")
        self.client.delete(f"/api/payments/{p.data['id']}/")
        self.assertEqual(Invoice.objects.get(pk=inv["id"]).status, "partial")

    def test_project_must_belong_to_client(self):
        other = Client.objects.create(name="Boshqa")
        r = self.client.post("/api/invoices/", {"client": other.pk, "project": self.project.pk, "amount": "10"})
        self.assertEqual(r.status_code, 400)

    def test_dashboard_finance_numbers(self):
        inv = self._invoice()
        self.client.post("/api/payments/", {"invoice": inv["id"], "amount": "300"})
        self.client.post("/api/expenses/", {"category": "office", "amount": "100"})
        fin = self.client.get("/api/reports/dashboard/").data["finance"]
        self.assertEqual(fin["revenue_month"], Decimal("300"))
        self.assertEqual(fin["profit_month"], Decimal("200"))
        self.assertEqual(fin["receivables"], Decimal("700"))


class LeadTests(BaseAPITest):
    def test_convert_lead(self):
        self.client.force_authenticate(self.admin)
        lead = Lead.objects.create(name="Yangi mijoz", phone="+998")
        r = self.client.post(f"/api/leads/{lead.pk}/convert/")
        self.assertEqual(r.status_code, 201)
        lead.refresh_from_db()
        self.assertEqual(lead.stage, "won")
        self.assertEqual(lead.client.name, "Yangi mijoz")
        self.assertEqual(self.client.post(f"/api/leads/{lead.pk}/convert/").status_code, 400)


class ReportTests(BaseAPITest):
    def test_project_report(self):
        self.client.force_authenticate(self.admin)
        Task.objects.create(project=self.project, title="a", status="done")
        Task.objects.create(project=self.project, title="b", due_date=timezone.localdate() - timedelta(days=1))
        r = self.client.get(f"/api/reports/projects/{self.project.pk}/")
        self.assertEqual(r.status_code, 200)
        self.assertEqual(r.data["tasks"], {"total": 2, "done": 1, "overdue": 1})
        self.assertIn("finance", r.data)
